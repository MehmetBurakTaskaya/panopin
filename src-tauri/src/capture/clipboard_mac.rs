//! macOS clipboard listener (D-073). macOS announces no pasteboard changes, so a thread compares
//! the pasteboard's change count twice a second (an integer read) and reads the pasteboard only
//! when the count moved. Like on Windows, it only fills a `Snapshot`; `admission` decides.

use std::{sync::mpsc::Sender, thread, time::Duration};

use objc2::rc::autoreleasepool;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF, NSWorkspace,
};

use super::{
    admission::{RawImage, Snapshot},
    Event,
};
use crate::error::Result;

/// Added to every copy Panopin makes, so its own copies are never captured again.
pub const OWN_TYPE: &str = "com.mehmetburaktaskaya.panopin.own-copy";
/// What password managers and other apps set on copies that must not be kept (nspasteboard.org).
const PRIVATE_TYPES: [&str; 4] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];
const FILE_URL: &str = "public.file-url";
const INTERVAL: Duration = Duration::from_millis(500);
/// How many more rounds a change that looked empty is read again before it counts as seen.
const EMPTY_RETRIES: u32 = 3;

pub fn spawn(tx: Sender<Event>) -> Result<()> {
    thread::Builder::new()
        .name("clipboard".into())
        .spawn(move || run(&tx))?;
    Ok(())
}

fn run(tx: &Sender<Event>) {
    // Whatever is on the pasteboard at start was copied before Panopin ran; it is not captured.
    let mut seen = autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount());
    let mut empty_reads = 0;
    loop {
        thread::sleep(INTERVAL);
        let snapshot = autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            let count = pasteboard.changeCount();
            if count == seen {
                return None;
            }
            let snapshot = read(&pasteboard);
            // An app clears the pasteboard and then writes to it, and the count moves only once:
            // read in between, the copy looks empty. It is read again before it counts as seen.
            if is_empty(&snapshot) && empty_reads < EMPTY_RETRIES {
                empty_reads += 1;
                return None;
            }
            seen = count;
            empty_reads = 0;
            Some(snapshot)
        });
        if let Some(snapshot) = snapshot {
            if tx.send(Event::Clipboard(snapshot)).is_err() {
                return;
            }
        }
    }
}

fn read(pasteboard: &NSPasteboard) -> Snapshot {
    let types: Vec<String> = pasteboard
        .types()
        .map(|types| types.to_vec().iter().map(|t| t.to_string()).collect())
        .unwrap_or_default();
    let has = |name: &str| types.iter().any(|t| t == name);
    // macOS names no pasteboard owner; the app in front made the copy.
    let front = frontmost_app();
    let mut snapshot = Snapshot {
        owner_exe: front.clone(),
        foreground_exe: front,
        private: PRIVATE_TYPES.iter().any(|t| has(t)),
        own_copy: has(OWN_TYPE),
        has_files: has(FILE_URL),
        ..Snapshot::default()
    };
    // Content is only read when no marker forbids it.
    if snapshot.private || snapshot.own_copy || snapshot.has_files {
        return snapshot;
    }
    // SAFETY: the pasteboard type constants are immutable statics provided by AppKit.
    let (string, png, tiff) = unsafe {
        (
            NSPasteboardTypeString,
            NSPasteboardTypePNG,
            NSPasteboardTypeTIFF,
        )
    };
    snapshot.text = pasteboard.stringForType(string).map(|s| s.to_string());
    let blank = snapshot
        .text
        .as_deref()
        .is_none_or(|t| t.chars().all(char::is_whitespace));
    if blank {
        snapshot.image = pasteboard
            .dataForType(png)
            .map(|data| RawImage::Png(data.to_vec()))
            .or_else(|| {
                pasteboard
                    .dataForType(tiff)
                    .map(|data| RawImage::Encoded(data.to_vec()))
            });
    }
    snapshot
}

/// Nothing to keep and no marker that says why: what a copy looks like before it is written.
fn is_empty(snapshot: &Snapshot) -> bool {
    snapshot.text.is_none()
        && snapshot.image.is_none()
        && !snapshot.private
        && !snapshot.own_copy
        && !snapshot.has_files
}

/// The executable name of the app in front, which the excluded-apps list matches.
fn frontmost_app() -> Option<String> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    app.localizedName().map(|name| name.to_string())
}
